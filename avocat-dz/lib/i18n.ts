export function t(lang: Lang, key: string): string {
  return translations[lang][key] ?? translations.ar[key] ?? key;
}

export function getLangFromStorage(): Lang {
  if (typeof window === "undefined") return "ar";
  const v = localStorage.getItem("maktabi-lang") as Lang | null;
  if (v && ["ar", "fr", "en"].includes(v)) return v;
  // try browser language
  const nav = navigator.language?.slice(0, 2);
  if (nav === "fr") return "fr";
  if (nav === "en") return "en";
  return "ar";
}

export function setLangStorage(lang: Lang) {
  localStorage.setItem("maktabi-lang", lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = LANGUAGES[lang].dir;
}
